/**
 * The Sakura District's story, as data: the notes left round Sakuragi, each telling what a place was, what happened
 * there when the city fell, and what is left of it seven springs on. Pure data (the co-op simulation and the journal
 * both read it).
 *
 * The story. Sakuragi was a ward of cherry trees, a shopping arcade, a canal and a hilltop school, with an old
 * theatre owned by the Kurenai family - whose pharmaceutical company had a laboratory under it. The fall began there:
 * a sickness the papers called kaika-byou, "the blooming", that turned people and made the cherry trees bloom out of
 * season wherever the dead lay. The Kurenai heiress, Sayo, an actress, was the lab's first patient; she is the
 * Crimson Empress now. The city tried everything - the evacuation point at the station, the army's checkpoint at the
 * freight yard, the school's barricades, the families' camp in the park, a soup kitchen, a radio - and every attempt
 * failed in its own way. The last train, the 21:47, never came; the last helicopter left the school full. The people
 * who stayed at the theatre made a court round the Empress and called her a goddess: the Kurenai Court, who feed her
 * and shoot outsiders.
 *
 * The shrine keeper, Aoi Kisaragi, kept the old festival's secret: the Thousand Lanterns, lit in the right order with
 * the shrine's five charms tied to the sacred tree, and the bell rung while the shrine's voice speaks - the night the
 * dead are seen home. Her notes lead the way. Last night the shrine relay began transmitting on its own.
 *
 * Notes marked `clue` carry the sakura stamp: they point at the Easter egg (`sakura/quest.ts`).
 */

